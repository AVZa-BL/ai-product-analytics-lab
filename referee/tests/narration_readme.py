"""The README section on `referee narrate`, made from the command's real output (design 24.14).

    python tests/narration_readme.py     # rewrite the block of README.md between its two markers

Run from `referee/`, with `src` and `tests` on `PYTHONPATH`. Every page and request the block shows
is printed by `referee.cli.main` in this process, on the committed report; the figures of the
held-out score, the freeze commit and the misses are read from `heldout_first_score.json`, and the
sentences around them are written here. Nothing else of README.md is touched: the status paragraph
and row 5 of the milestone table are hand-written, and `test_narration_readme.py` keeps them equal
to the words of design 24.14 and to the figures of `docs/grounding-study.json`.

No git and no network. The one process started is the `cat` that replays a selection (24.5), so
this is for POSIX, like the command it shows.
"""

import argparse
import contextlib
import io
import json
import shlex
import sys
import tempfile
from collections.abc import Sequence
from pathlib import Path

from narration_evaluation import describe, rate_cell

from referee.cli import main as referee

ROOT = Path(__file__).resolve().parents[1]  # referee/
README = ROOT / "README.md"
GOLDEN = "tests/golden/offer-page-results.json"
QUESTIONS = "tests/data/narration_eval/public_questions.json"
SCORE = "tests/data/narration_eval/heldout_first_score.json"
BEGIN = "<!-- BEGIN narration (generated by python tests/narration_readme.py; do not edit) -->"
END = "<!-- END narration -->"
SCHEMA = "referee-narration-output/1"
REQUEST_HEAD = 1000  # characters of the request that the block shows
PAGE_HEAD = 20  # lines of the page of the replay that the block shows: through its first finding

PROVENANCE = (
    "By default no language model runs when you use this command; with --llm-command, a command "
    "you name may call one. Language-model agents wrote the code, tests, labels and reviews and "
    "every question except the three quoted from the design document; no human labelled a "
    "question."
)
WHAT = (
    "`python -m referee narrate REPORT [--question TEXT]` reads a saved results report, the JSON "
    "of `review-results --format json`, and prints one page about it. It answers four kinds of "
    "question by code, with the engine's own sentences and the report's numbers rounded to six "
    "significant digits: a summary of the review, one finding explained, what to do next, and what "
    "was checked. It refuses by code what its router, a table of words and not a model, "
    "recognises as another kind of question (a request to ship or to stop, to be told that the "
    "experiment is fine, for the effect's numbers, for a forecast, for a breakdown the report "
    "does not hold, and so on), and a question it does not recognise as one of the four. The page "
    "is advice and not a gate: every page ends by saying that its exit status does not mean the "
    "experiment is valid, so do not write `referee narrate report.json && ship`. "
    "[`docs/narration.md`](docs/narration.md) has the contract: what the page guarantees and what "
    "it does not, the exit statuses, and what the command reads."
)
PUBLIC = (
    "Three questions quoted in the design document, put to the report of the example under "
    "'Reviewing results' (committed as `tests/golden/offer-page-results.json`; its verdict is "
    "invalid). None is one of the four kinds, so each is refused: the page says what it "
    "understood the question as, without repeating its words, prints the Decision section of the "
    "report's memo, says what the layer does not do for that kind of question, and points into "
    "the report. Each page is whole, as the command above it printed it, with exit status 0: a "
    "page was printed, whatever the verdict (`review-results` exits 1 on an invalid report)."
)
SCORED = (
    "The router's first score was taken once, on {questions} questions that language-model "
    "agents wrote and labelled, and that were held out from its construction by procedure and "
    "not by a technical barrier. Git can show that the narration modules the router loads were "
    "frozen before it was scored (freeze commit "
    "`{freeze}`); it does not show that nobody had read the half. The figures are agreement with "
    "the agent-authored taxonomy, as k of n with 95% Clopper-Pearson intervals. They say nothing "
    "about usefulness, readability, a model's behaviour or real users' phrasing, none of which "
    "was measured, and the router is not injection-proof and its twelve categories are not "
    "complete. Of the {refusal} questions labelled with refusal categories:"
)
MISSES = (
    "All {count} misses of the first score, each with its index in the half, its kind, its label, "
    "what the router returned and the question verbatim as a JSON string:"
)
EVALUATION = (
    "[`docs/narration-evaluation.md`](docs/narration-evaluation.md) puts the first score beside a "
    "fresh run of the router, and says how the freeze was checked and what the half does not show."
)
EGRESS = (
    "**`--llm-command` sends the report's counts, p values, rates and allocations to whatever the "
    "command contacts.** The arms' names become `A1` (the control), `A2`, `A3`, which hides the "
    "names and nothing else: aliases are not anonymisation. `--show-request` prints what would "
    "leave. Referee does not control what the command does with it."
)
COMMAND = (
    "`--llm-command CMD` runs only a command you name, once, and only for a summary, the next "
    "steps or the explanation of one finding; without it no process is started. The command's "
    "part is selection by identifier and never wording: it is given a sheet in which each "
    "sentence and fact of the findings in scope has an identifier, and returns identifiers "
    "only, so it chooses what leads under `Selected:` while code prints the rest of what the "
    "question permits under `Not selected by the narrator:`, every sentence being the engine's "
    "own. It never sees your question, only the kind of question and the rule it names. The "
    "selection does not make the page relevant, and the labels are no ranking. `--show-request` "
    "prints the exact request the command would receive, one line of JSON, and starts nothing; "
    "the first {shown} of its {size:,} characters:"
)
REPLAY = (
    "A file can stand in for the command: `cat selection.json` ignores the request it is sent "
    "and prints the file, so the path can be followed with no model. `selection.json` holds one "
    "reason for each finding of the report. The page starts like this (its first {shown} of "
    "{lines} lines):"
)
NEVER = (
    "**The model path has never been run with a model.** It has met only fake narrators and a "
    "stub command, so what a model would return is not known. Referee ships no wrapper for a "
    "model provider, no default command and no `--model` option."
)


def run(root: Path, *args: str) -> str:
    """The standard output of `referee narrate GOLDEN ARGS`, which must exit 0."""
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        status = referee(["narrate", str(root / GOLDEN), *args])
    if status != 0:
        raise RuntimeError(
            f"referee narrate {' '.join(args)} gave status {status}: {err.getvalue()}"
        )
    return out.getvalue()


def fence(kind: str, *lines: str) -> str:
    return "\n".join([f"```{kind}", *lines, "```"])


def page_lines(page: str) -> list[str]:
    return page.rstrip("\n").split("\n")


def refusals(root: Path) -> str:
    questions = json.loads((root / QUESTIONS).read_text(encoding="utf-8"))["questions"]
    parts = []
    for question in questions:
        text = question["text"]
        command = f'python -m referee narrate {GOLDEN} --question "{text}"'
        parts += [fence("bash", command), fence("text", *page_lines(run(root, "--question", text)))]
    return "\n\n".join(parts)


def scored(root: Path) -> str:
    first = json.loads((root / SCORE).read_text(encoding="utf-8"))
    head, answerable, base = first["headline"], first["answerable"], first["baselines"]
    bullets = [
        f"- Strict: {rate_cell(head['strict'])}: the router's first category is in the label.",
        f"- Other: {rate_cell(head['other'])}: it refused, but its first category is not in the "
        "label.",
        f"- Answered: {rate_cell(head['answered'])}: it returned an answer, not a refusal.",
        f"- Refused at all (strict plus other): the router {rate_cell(head['refused_at_all'])}; a "
        "baseline that refuses on a list of trigger words "
        f"{rate_cell(base['triggers']['refused_at_all'])}; a baseline that answers when an intent "
        f"keyword matches {rate_cell(base['keywords']['refused_at_all'])}.",
        f"- False refusal, of the {answerable['n']} questions labelled with one of the four kinds: "
        f"the router {rate_cell(answerable['false_refusal'])}; the trigger words "
        f"{rate_cell(base['triggers']['false_refusal'])}; the intent keywords "
        f"{rate_cell(base['keywords']['false_refusal'])}.",
        f"- Wrong intent or target, of the same {answerable['n']}: the router "
        f"{rate_cell(answerable['wrong'])}; it answered something else.",
    ]
    misses = [
        f"- {miss['index']} ({miss['kind']}): label {describe(miss['label'])}; router "
        f"{describe(miss['router_result'])}; {json.dumps(miss['text'], ensure_ascii=False)}"
        for miss in first["misses"]
    ]
    return "\n\n".join(
        [
            SCORED.format(
                questions=first["questions"], freeze=first["freeze_sha"], refusal=head["n"]
            ),
            "\n".join(bullets),
            MISSES.format(count=len(misses)),
            "\n".join(misses),
            EVALUATION,
        ]
    )


def model_path(root: Path) -> str:
    report = json.loads((root / GOLDEN).read_text(encoding="utf-8"))
    chosen = json.dumps(
        {
            "schema": SCHEMA,
            "findings": [
                {"id": f["rule_id"], "facts": [], "sentences": [f"{f['rule_id']}.why.1"]}
                for f in report["findings"]
            ],
        }
    )
    with tempfile.TemporaryDirectory() as folder:
        file = Path(folder) / "selection.json"
        file.write_text(chosen + "\n", encoding="utf-8")
        command = f"cat {shlex.quote(str(file))}"  # the page does not hold the path
        request = run(root, "--llm-command", command, "--show-request").rstrip("\n")
        replay = page_lines(run(root, "--llm-command", command))
    shown = f'python -m referee narrate {GOLDEN} --llm-command "cat selection.json"'
    return "\n\n".join(
        [
            EGRESS,
            COMMAND.format(shown=REQUEST_HEAD, size=len(request)),
            fence("bash", f"{shown} --show-request"),
            fence("text", request[:REQUEST_HEAD] + " ..."),
            REPLAY.format(shown=PAGE_HEAD, lines=len(replay)),
            fence("bash", f"cat > selection.json <<'EOF'\n{chosen}\nEOF\n{shown}"),
            fence("text", *replay[:PAGE_HEAD], "..."),
            NEVER,
        ]
    )


def render_block(root: Path = ROOT) -> str:
    """The text between the markers, without the marker lines and without a final newline."""
    return "\n\n".join(
        [
            PROVENANCE,
            WHAT,
            PUBLIC,
            refusals(root),
            "### The router on the held-out half",
            scored(root),
            "### With `--llm-command`",
            model_path(root),
        ]
    )


def span(lines: list[str]) -> tuple[int, int]:
    """The indices of the two marker lines, which must each occur once, the first first."""
    begin, end = ([i for i, line in enumerate(lines) if line == m] for m in (BEGIN, END))
    if len(begin) != 1 or len(end) != 1 or begin[0] > end[0]:
        raise ValueError(f"README.md needs one line {BEGIN!r} and, after it, one line {END!r}")
    return begin[0], end[0]


def current(readme: str) -> str:
    """The block as `readme` holds it."""
    lines = readme.split("\n")
    begin, end = span(lines)
    return "\n".join(lines[begin + 1 : end])


def splice(readme: str, block: str) -> str:
    """`readme` with its block replaced by `block`, and nothing else changed."""
    lines = readme.split("\n")
    begin, end = span(lines)
    return "\n".join([*lines[: begin + 1], block, *lines[end:]])


def main(argv: Sequence[str] | None = None, *, readme: Path = README) -> int:
    argparse.ArgumentParser(description=__doc__.split("\n")[0]).parse_args(argv)
    text = readme.read_text(encoding="utf-8")
    readme.write_text(splice(text, render_block()), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
